def card_resp(sid):
    m = {"declined": ("done", None), "card_used": ("done", None), "card_stale": ("stale", None),
         "not_allowed_now": ("stale", None), "card_expired": ("expired", None), "card_not_yours": ("permission", None),
         "not_accepting": ("permission", None), "retry_needed": ("error", None), "server_error": ("error", None)}
    for other, outcome in CARD_OWN.items():
        if other == sid:
            m[outcome] = ("done", None)
        else:
            m[outcome] = ("-", "이 카드에서는 나오지 않음(%s %s의 결과)" % (other, CARD_NAME[other]))
    m["day_full"] = ("day-full", None) if sid == "SCR-004" else ("-", "주문 요청 카드(SCR-004)에서만 나옴")
    # 설계 재검토 H11: 주문자 정보 블록(SCR-004#orderer)과 입금자 이름 블록(SCR-006#depositor)
    m["orderer_saved"] = (("normal", "주문자 정보 블록의 값을 남긴 뒤 이 카드가 나옴(SPEC-072)") if sid == "SCR-004"
                          else ("-", "주문자 정보 블록(SCR-004#orderer)의 결과라 이 카드에서는 나오지 않음"))
    # 설계 재검토 H8: 채널 연결 확인의 시험 버튼이 부른 결과(SCR-003#link-test)
    for k in ("block_verified", "channel_linked"):
        m[k] = ("-", "채널 연결 확인의 시험 버튼 결과라 이 카드에서는 나오지 않음(SCR-003#link-test)")
    m["input_invalid"] = {"SCR-004": ("orderer", None), "SCR-006": ("depositor", None)}.get(
        sid, ("-", "주문자 정보·알레르기 답·입금자 이름 블록(SCR-004#orderer, SCR-004#allergy, SCR-006#depositor)에서만 나옴"))
    # 설계 재검토 H5: 알레르기 정보 카드(SCR-004#allergy). 결과로 주문자 정보 카드나 주문 요청 카드가 나옴
    for k in ("allergy_saved", "allergy_declined"):
        m[k] = (("orderer", None) if sid == "SCR-004"
                else ("-", "알레르기 정보 카드(SCR-004#allergy)의 결과라 이 카드에서는 나오지 않음"))
    # 설계 재검토 H10: 완성 사진 안내의 사진 게시 동의 카드(SCR-011#photo-consent)
    m["photo_consent_saved"] = ("-", "완성 사진 안내의 사진 게시 동의 카드 결과라 이 카드에서는 나오지 않음(SCR-011#photo-consent)")
    # 설계 재검토 M5: 결제 안내의 새 금액 확인 카드(SCR-005#amount-confirm)
    for k in ("amount_confirmed", "amount_declined"):
        m[k] = ("-", "결제 안내의 새 금액 확인 카드 결과라 이 카드에서는 나오지 않음(SCR-005#amount-confirm)")
    return {"API-071#200:" + k: v for k, v in m.items()}


