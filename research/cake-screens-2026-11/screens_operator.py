def s_op_perm(extra=""):
    """운영자 화면의 401: 운영자 로그인으로 보내고 돌아옴(08단계 결정 W9)."""
    t = ("운영자 로그인이 없거나 만료됐거나 운영자 계정이 아님(401 unauthenticated): 운영자 로그인(SCR-046)으로 이동하고, "
         "로그인하면 이 화면으로 돌아옴('다시 로그인해 주세요'). 이동하기 전에도 운영자 기록은 하나도 보이지 않음(G1, 06단계 DEC-11)")
