def add(name, pat, repl, **kw):
    RULES.append(Rule(name, pat, repl, **kw))


Q = "(?P<Q>['’\"”]?)"


def noun(name, old, new, pre=r"(?<![가-힣])", post="", **kw):
    add(name, pre + "(?:" + old + ")" + post + Q + "{J}", new + r"\g<Q>{J}", **kw)


def phrases(name, pairs, josa=False, pre="", **kw):
    for old, new in sorted(pairs, key=lambda x: -len(x[0])):
        if josa:
            add(name, pre + re.escape(old) + Q + "{J}", new.replace("\\", "\\\\") + r"\g<Q>{J}", **kw)
        else:
            add(name, pre + re.escape(old), new.replace("\\", "\\\\"), **kw)


def verb(name, old, new, noun_new=None, pre=r"(?<![가-힣])", extra=(), post="", **kw):
    """old/new: 활용 자리별 글자. B 어간(자음 어미 앞), B2 으-어간, A 아/어형, P 과거, N ㄴ관형, F ㄹ관형, M ㅁ명사형, H ㅂ니다."""
    for o, n in extra:
        add(name, pre + re.escape(o), n, **kw)
    inv = {}
    for k, v in old.items():
        if k == "M":
            continue
        inv.setdefault(v, []).append(k)
    alts = sorted(inv, key=len, reverse=True)

    def rep(m):
        v = m.group("V")
        ks = inv[v]
        if len(ks) > 1:  # 어간과 아/어형이 같은 글자(돌려보내)
            nxt = m.string[m.end():m.end() + 1]
            k = "B" if re.match("[가-힣]", nxt) else "A"
        else:
            k = ks[0]
        return new[k]
    add(name, pre + "(?P<V>" + "|".join(map(re.escape, alts)) + ")" + post + "(?=[가-힣\\s.,·)(:;'\"<|/\\]-]|$)", rep, **kw)
    if "M" in old:
        mo = re.escape(old["M"])

        def repm(m):
            j = m.group("J") or ""
            if j and noun_new:
                return noun_new + agree(noun_new, j)
            nxt = m.string[m.end():m.end() + 2]
            prv = m.string[max(0, m.start() - 3):m.start()]
            # 명사로 쓰인 자리: 'X마다', 'X·Y', '(X', '"X"', '몇 번째 X'
            if noun_new and (nxt.startswith(("마다", "·", "별")) or prv[-1:] in ("·", "(", '"') or prv.endswith("번째 ")):
                return noun_new
            return new["M"] + (agree(new["M"], j) if j else "")
        add(name + " (명사형)", pre + mo + "{J}", repm, **kw)


